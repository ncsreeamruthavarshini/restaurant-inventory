BEGIN;

-- 1. Restaurant workspaces
CREATE TABLE IF NOT EXISTS restaurants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. User accounts: one account belongs to one restaurant.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL
        REFERENCES restaurants(id) ON DELETE RESTRICT,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Create a workspace for existing records.
INSERT INTO restaurants (name)
SELECT 'Olive & Thyme'
WHERE NOT EXISTS (
    SELECT 1 FROM restaurants WHERE name = 'Olive & Thyme'
);

-- 4. Add nullable ownership columns first so existing records are preserved.
ALTER TABLE ingredients
    ADD COLUMN IF NOT EXISTS restaurant_id BIGINT
        REFERENCES restaurants(id) ON DELETE RESTRICT;

ALTER TABLE menu_items
    ADD COLUMN IF NOT EXISTS restaurant_id BIGINT
        REFERENCES restaurants(id) ON DELETE RESTRICT;

ALTER TABLE waste_records
    ADD COLUMN IF NOT EXISTS restaurant_id BIGINT
        REFERENCES restaurants(id) ON DELETE RESTRICT;

-- 5. Associate existing records with the legacy workspace.
UPDATE ingredients
SET restaurant_id = (
    SELECT id FROM restaurants WHERE name = 'Olive & Thyme'
)
WHERE restaurant_id IS NULL;

UPDATE menu_items
SET restaurant_id = (
    SELECT id FROM restaurants WHERE name = 'Olive & Thyme'
)
WHERE restaurant_id IS NULL;

UPDATE waste_records
SET restaurant_id = (
    SELECT id FROM restaurants WHERE name = 'Olive & Thyme'
)
WHERE restaurant_id IS NULL;

-- 6. Require ownership for all future records.
ALTER TABLE ingredients
    ALTER COLUMN restaurant_id SET NOT NULL;

ALTER TABLE menu_items
    ALTER COLUMN restaurant_id SET NOT NULL;

ALTER TABLE waste_records
    ALTER COLUMN restaurant_id SET NOT NULL;

-- 7. Menu names are unique within a restaurant, not globally.
ALTER TABLE menu_items
    DROP CONSTRAINT IF EXISTS menu_items_name_key;

CREATE UNIQUE INDEX IF NOT EXISTS
    menu_items_restaurant_name_key
    ON menu_items (restaurant_id, name);

COMMIT;
